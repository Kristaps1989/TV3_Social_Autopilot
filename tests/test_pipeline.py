def test_kill_switch_holds_queue(session):
    article = make_article(session, guid="e2e-4", url="https://tv3.lv/d",
                          canonical_url="https://tv3.lv/d",
                          title="Cits unikāls virsraksts par kultūru")
    run_decisions(session)
    posts = session.execute(
        select(Post).where(Post.article_id == article.id)).scalars().all()
    assert posts
    for p in posts:
        p.scheduled_at = utcnow() - timedelta(minutes=1)
    set_setting(session, "kill_switch", "on")
    n = publish_due(session)
    assert n == 0
    for p in posts:
        session.refresh(p)
        assert p.state == "scheduled"  # held, not lost
    set_setting(session, "kill_switch", "")


def test_no_duplicate_posts_per_channel(session):
    article = make_article(session, guid="e2e-5", url="https://tv3.lv/e",
                          canonical_url="https://tv3.lv/e",
                          title="Vēl viens pilnīgi atšķirīgs stāsts")
    run_decisions(session)
    first = session.execute(
        select(Post).where(Post.article_id == article.id)).scalars().all()
    article.decided_at = None  # simulate re-decision (e.g. status refresh)
    session.commit()
    run_decisions(session)
    second = session.execute(
        select(Post).where(Post.article_id == article.id)).scalars().all()
    assert len(second) == len(first), "same article+channel must not be scheduled twice"
